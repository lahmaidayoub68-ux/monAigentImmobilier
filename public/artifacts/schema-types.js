export const SCHEMA_BY_ID = Object.fromEntries(
  SCHEMA_TYPES.map(([id, label, cat, renderer, frame, norm]) => [
    id,
    { id, label, cat, renderer, frame, norm },
  ]),
);
const BY_RENDERER = {};
SCHEMA_TYPES.forEach(([id, , , r]) => (BY_RENDERER[r] = BY_RENDERER[r] || id));
export const schemaEntry = (a) =>
  SCHEMA_BY_ID[a.schemaType] ||
  SCHEMA_BY_ID[BY_RENDERER[a.semanticType]] || {
    label: "Schéma",
    cat: "Schéma",
    frame: "explain",
    norm: "",
  };
